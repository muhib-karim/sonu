import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";
import tailwindcss from "@tailwindcss/vite";
import { resolve } from "path";

const host = process.env.TAURI_DEV_HOST;

// https://vitejs.dev/config/
export default defineConfig(async ({ mode }) => {
  const plugins = [
    react({
      // Enable Fast Refresh for better development experience
      fastRefresh: true,
      // JSX runtime optimization
      jsxRuntime: "automatic",
    }),
    tailwindcss(),
  ];

  // Add visualizer plugin in analyze mode (optional)
  if (mode === "analyze") {
    try {
      const { visualizer } = await import("rollup-plugin-visualizer");
      plugins.push(
        visualizer({
          open: true,
          gzipSize: true,
          brotliSize: true,
          filename: "dist/stats.html",
        }),
      );
    } catch {
      console.warn(
        "rollup-plugin-visualizer not installed. Skipping bundle analysis.",
      );
    }
  }

  return {
    plugins,

    // Vitest reads the `test` block from this file when no
    // vitest.config.ts exists (kept here to avoid a duplicate config).
    test: {
      globals: true,
      environment: "jsdom",
      setupFiles: ["./src/test/setup.ts"],
      coverage: {
        provider: "v8",
        reporter: ["text", "json", "json-summary", "html"],
        // Every source file counts, including the ones no test imports.
        // Without `include`, Vitest only reports files a test happened to
        // load, which makes the percentage look far better than it is.
        include: ["src/**/*.{ts,tsx}"],
        exclude: [
          "dist/**",
          // Test files and the Vitest setup are not product code.
          "src/test/**",
          "src/**/__tests__/**",
          "src/**/*.test.{ts,tsx}",
          "src/**/*.d.ts",
          // Generated by tauri-specta.
          "src/bindings.ts",
        ],
        // A ratchet, not a target (same idea as scripts/panic-baseline.txt).
        // Each floor sits just under the measured figure: the largest
        // half-point step that is at least a quarter point below it (the
        // slack absorbs small differences between Node/V8 versions).
        // Coverage may rise freely; a change that lowers it fails
        // `bun run test:coverage` and CI. When you add tests, raise the
        // floors in the same commit so the gain sticks. Do not lower them to
        // make a change pass.
        //
        // Measured 2026-11-10 (159 tests):
        //   all files        statements 14.98, branches 13.30, functions 13.78, lines 14.95
        //   settingsStore.ts statements 87.77, branches 90.47, functions 64.10, lines 87.27
        thresholds: {
          statements: 14.5,
          branches: 13,
          functions: 13.5,
          lines: 14.5,
          // The store is the single source of truth for settings and every
          // write goes through it, so it gets its own, much higher floor.
          // In a single file one statement is worth about half a point and
          // one branch about one point, so each floor leaves room for one
          // unit of difference between Node/V8 versions and no more.
          "src/stores/settingsStore.ts": {
            statements: 87,
            branches: 89,
            functions: 62.5,
            lines: 86.5,
          },
        },
      },
      include: ["src/**/*.test.{ts,tsx}"],
      exclude: ["node_modules", "dist", ".git", ".cache"],
    },

    // Path aliases for cleaner imports
    resolve: {
      alias: {
        "@": resolve(__dirname, "./src"),
        "@/bindings": resolve(__dirname, "./src/bindings.ts"),
        "@/components": resolve(__dirname, "./src/components"),
        "@/lib": resolve(__dirname, "./src/lib"),
        "@/hooks": resolve(__dirname, "./src/hooks"),
        "@/stores": resolve(__dirname, "./src/stores"),
      },
    },

    // Build optimization
    build: {
      // Target modern browsers for smaller bundles
      target: "es2020",
      // Enable minification
      minify: "esbuild",
      // Generate source maps for debugging
      sourcemap: mode !== "production",
      // Optimize chunk size
      chunkSizeWarningLimit: 1000,
      // Rollup options for better bundling
      rollupOptions: {
        input: {
          main: resolve(__dirname, "index.html"),
          overlay: resolve(__dirname, "src/overlay/index.html"),
        },
        output: {
          // Manual chunk splitting for better caching
          manualChunks: {
            // Vendor libraries that change infrequently
            vendor: [
              "react",
              "react-dom",
              "react-i18next",
              "i18next",
              "zustand",
            ],
            // UI components
            ui: ["lucide-react", "sonner"],
            // Tauri plugins
            tauri: ["@tauri-apps/api", "@tauri-apps/plugin-store"],
          },
          // Optimize entry chunk size
          entryFileNames: "assets/[name]-[hash].js",
          chunkFileNames: "assets/[name]-[hash].js",
          assetFileNames: "assets/[name]-[hash].[ext]",
        },
      },
      // Enable CSS code splitting
      cssCodeSplit: true,
      // Assets inline threshold (8KB)
      assetsInlineLimit: 8192,
    },

    // Optimize dependencies
    optimizeDeps: {
      // Pre-bundle these dependencies for faster dev server startup
      include: [
        "react",
        "react-dom",
        "react-i18next",
        "i18next",
        "zustand",
        "lucide-react",
      ],
    },

    // Esbuild optimizations
    esbuild: {
      // Drop console logs in production
      drop: mode === "production" ? ["console", "debugger"] : [],
      // Optimize JSX
      jsx: "automatic",
      // Target modern JS
      target: "es2020",
    },

    // Vite options tailored for Tauri development
    clearScreen: false,

    server: {
      port: 1420,
      strictPort: true,
      host: host || false,
      hmr: host
        ? {
            protocol: "ws",
            host,
            port: 1421,
          }
        : undefined,
      watch: {
        // Ignore watching Rust files and build outputs
        ignored: ["**/src-tauri/**", "**/target/**", "**/dist/**"],
      },
      // Enable compression for dev server
      fs: {
        strict: true,
        allow: ["."],
      },
    },

    // Preview server configuration
    preview: {
      port: 1420,
      strictPort: true,
    },

    // CSS optimizations
    css: {
      // Enable CSS modules
      modules: {
        localsConvention: "camelCase",
      },
      // PostCSS configuration
      postcss: {
        plugins: [],
      },
      // Dev sourcemaps
      devSourcemap: true,
    },
  };
});
